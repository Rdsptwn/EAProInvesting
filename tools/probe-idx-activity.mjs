import { chromium } from 'playwright';
const b = await chromium.launch();
const ctx = await b.newContext({ userAgent: 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36', locale: 'en-US' });
const pg = await ctx.newPage();
await pg.goto('https://www.idx.id/en/market-data/trading-summary/stock-summary/', { waitUntil: 'networkidle', timeout: 45000 }); await pg.waitForTimeout(4000);
const j = await pg.evaluate(async () => (await fetch('/primary/TradingSummary/GetStockSummary?length=9999&start=0', { headers: { Accept: 'application/json' } })).json());
console.log('KEYS', Object.keys(j.data[0]).join(','));
const sums = {}; for (const r of j.data) for (const [k, v] of Object.entries(r)) if (typeof v === 'number' && /Volume|Value|Freq/i.test(k)) sums[k] = (sums[k] || 0) + v;
console.log('SUMS', JSON.stringify(sums));
const idx = await pg.evaluate(async () => (await fetch('/primary/TradingSummary/GetIndexSummary?length=9999&start=0')).json());
console.log('COMPOSITE', JSON.stringify(idx.data.find((x) => x.IndexCode === 'COMPOSITE')));
console.log('DATE', j.data[0].Date, 'n', j.data.length);
await b.close();
